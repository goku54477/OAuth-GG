export async function GET(request: Request) {
  const { searchParams } = new URL(request.url);
  const search = searchParams.get("search")?.toLowerCase().trim();
  const category = searchParams.get("category")?.toLowerCase().trim();
  const managedOnly = searchParams.get("managedOnly") === "true";

  // Try dynamic import from @/lib/catalog if available (merged from WS1)
  let toolkits: ComposioToolkitSummary[] = SEED_TOOLKITS;

  try {
    const catalogPath: string = "@/lib/catalog";
    const catalogModule = await import(catalogPath);
    if (catalogModule && typeof catalogModule.getCatalogToolkits === "function") {
      const dynamicToolkits = await catalogModule.getCatalogToolkits({
        search,
        category,
        managedOnly,
      });
      if (Array.isArray(dynamicToolkits) && dynamicToolkits.length > 0) {
        toolkits = dynamicToolkits;
      }
    }
  } catch {
    // Graceful fallback to built-in seed dataset
  }

  // Filter toolkits based on parameters
  const filtered = toolkits.filter((item) => {
    if (managedOnly && !item.hasManagedOAuth) return false;
    if (category && category !== "all") {
      const matchCat = item.categories.some((c) => c.toLowerCase() === category);
      if (!matchCat) return false;
    }
    if (search) {
      const matchSearch =
        item.name.toLowerCase().includes(search) ||
        item.slug.toLowerCase().includes(search) ||
        item.description.toLowerCase().includes(search);
      if (!matchSearch) return false;
    }
    return true;
  });

  const managedOAuthCount = toolkits.filter((t) => t.hasManagedOAuth).length;
  const categories = [...new Set(toolkits.flatMap((t) => t.categories))].sort();

  return NextResponse.json({
    toolkits: filtered,
    stats: {
      totalToolkits: toolkits.length,
      managedOAuthCount,
      customOnlyCount: toolkits.length - managedOAuthCount,
      categories,
    },
  });
}
